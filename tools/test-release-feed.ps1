#Requires -Version 5.1
<#
.SYNOPSIS
    Guards the auto-update feed: it must stay public and token-free.

.DESCRIPTION
    The v2.5.6-3.1.4 builds shipped publish.private=true with a PAT embedded
    into the generated app-update.yml. When that token was revoked, every
    update check on those installs began to hard-fail with HTTP 401 - and no
    later release could ever reach them. This test makes that configuration
    impossible to ship again. It fails if:

      A. package.json's publish config stops being the public GitHub feed for
         bypass-zzzz/windows-tweaks (explicit private:false, no token field,
         no token-looking value anywhere in the block),
      B. any tracked file contains a GitHub token shape (github_pat_ / ghp_ /
         gho_ / ghu_ / ghs_ / ghr_), or a tracked app-update.yml exists at all
         (it must always be generated by electron-builder, never committed),
      C. any built app-update.yml under dist\ carries private:true or a token
         line (checked only when a build is present).

    release.ps1 runs this as a pre-flight gate, so a bad feed can never be
    published even if someone edits package.json by hand.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File tools\test-release-feed.ps1
#>
[CmdletBinding()]
param(
    [string]$Root
)

$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

if (-not $Root) {
    $here = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
    $Root = Split-Path -Parent $here
}
$pkgPath = Join-Path $Root 'package.json'
if (-not (Test-Path -LiteralPath $pkgPath)) { Write-Error "package.json not found: $pkgPath"; exit 1 }

$pass = 0
$fail = 0
function Assert-True {
    param([string]$What, [bool]$Condition, [string]$Detail)
    if ($Condition) {
        $script:pass++
        Write-Host ("  PASS  {0}" -f $What) -ForegroundColor Green
    } else {
        $script:fail++
        Write-Host ("  FAIL  {0}{1}" -f $What, $(if ($Detail) { "  -> $Detail" } else { '' })) -ForegroundColor Red
    }
}

# Token shapes GitHub actually issues. Matches are NEVER printed - a hit is
# reported by file name only, so a leaked token is not echoed into logs.
$tokenPattern = 'github_pat_[A-Za-z0-9_]{20,}|ghp_[A-Za-z0-9]{20,}|gho_[A-Za-z0-9]{20,}|ghu_[A-Za-z0-9]{20,}|ghs_[A-Za-z0-9]{20,}|ghr_[A-Za-z0-9]{20,}'

Write-Host "`n=== RELEASE FEED GUARD TEST ===" -ForegroundColor Cyan
Write-Host "root: $Root"

# ── A. package.json publish config ───────────────────────────────────────────
Write-Host "`n--- A. publish config ---" -ForegroundColor Cyan
$pkg = Get-Content -LiteralPath $pkgPath -Raw | ConvertFrom-Json
$targets = @($pkg.build.publish)
Assert-True 'A. package.json carries build.publish' (($targets.Count -ge 1) -and ($null -ne $targets[0])) 'build.publish is missing'

$badProvider = @()
$badPrivate = @()
$badToken = @()
foreach ($t in $targets) {
    $names = @($t.PSObject.Properties.Name)
    $okProvider = ($t.provider -eq 'github') -and ($t.owner -eq 'bypass-zzzz') -and ($t.repo -eq 'windows-tweaks')
    $okPrivate  = ($names -contains 'private') -and ($t.private -is [bool]) -and ($t.private -eq $false)
    $noToken    = -not ($names -contains 'token')
    $noTokeny   = -not (($t | ConvertTo-Json -Compress) -match $tokenPattern)
    if (-not $okProvider) { $badProvider += ("provider/owner/repo is '{0}/{1}/{2}'" -f $t.provider, $t.owner, $t.repo) }
    if (-not $okPrivate)  { $badPrivate += 'a publish target without explicit private:false' }
    if (-not ($noToken -and $noTokeny)) { $badToken += 'a publish target with a token field or token-looking value' }
}
Assert-True 'A. every publish target is the public bypass-zzzz/windows-tweaks GitHub feed' ($badProvider.Count -eq 0) ($badProvider -join ' | ')
Assert-True 'A. every publish target pins private:false explicitly' ($badPrivate.Count -eq 0) ($badPrivate -join ' | ')
Assert-True 'A. no publish target carries a token field or token-looking value' ($badToken.Count -eq 0) ($badToken -join ' | ')

# ── B. tracked files ─────────────────────────────────────────────────────────
Write-Host "`n--- B. tracked files ---" -ForegroundColor Cyan
$tracked = & git -C $Root ls-files 2>$null
if (-not $tracked) { Write-Error 'git ls-files returned nothing; is this a git working tree?'; exit 1 }

$binaryExt = @('.ico', '.png', '.jpg', '.jpeg', '.gif', '.exe', '.dll', '.zip', '.7z', '.woff', '.woff2', '.ttf')
$scanHits = @()
$scanned = 0
foreach ($rel in $tracked) {
    $ext = [System.IO.Path]::GetExtension($rel).ToLowerInvariant()
    if ($binaryExt -contains $ext) { continue }
    $full = Join-Path $Root ($rel -replace '/', '\')
    if (-not (Test-Path -LiteralPath $full)) { continue }
    try { $text = [System.IO.File]::ReadAllText($full) } catch { continue }
    $scanned++
    if ($text -match $tokenPattern) { $scanHits += $rel }
}
Assert-True ("B. no tracked file contains a GitHub token shape ({0} text files scanned)" -f $scanned) ($scanHits.Count -eq 0) ($scanHits -join ', ')

$trackedUpdateYml = @($tracked | Where-Object { [System.IO.Path]::GetFileName($_) -eq 'app-update.yml' })
Assert-True 'B. no app-update.yml is tracked (it must stay generated only)' ($trackedUpdateYml.Count -eq 0) ($trackedUpdateYml -join ', ')

# ── C. built artifacts (only when a build is present) ────────────────────────
Write-Host "`n--- C. built artifacts ---" -ForegroundColor Cyan
$distDir = Join-Path $Root 'dist'
$builtUpdateYmls = @()
if (Test-Path -LiteralPath $distDir) {
    $builtUpdateYmls = @(Get-ChildItem -LiteralPath $distDir -Recurse -Filter 'app-update.yml' -File -ErrorAction SilentlyContinue)
}
if ($builtUpdateYmls.Count -eq 0) {
    Write-Host '  (no built app-update.yml present - pre-build state, nothing to inspect)' -ForegroundColor DarkGray
    $pass++
} else {
    foreach ($yml in $builtUpdateYmls) {
        $rel = $yml.FullName.Substring($Root.Length).TrimStart('\')
        $text = Get-Content -LiteralPath $yml.FullName -Raw
        Assert-True ("C. {0}: provider is github and private:false" -f $rel) `
            (($text -match '(?m)^\s*provider:\s*github\s*$') -and ($text -match '(?m)^\s*private:\s*false\s*$')) `
            (($text -split "`n" | Where-Object { $_ -match 'provider|private' }) -join ' / ')
        Assert-True ("C. {0}: no token line, no private:true" -f $rel) `
            (-not ($text -match '(?mi)^\s*token\s*:') -and -not ($text -match '(?m)^\s*private:\s*true\s*$')) `
            'a token line or private:true was found'
    }
}

# ── Verdict ──────────────────────────────────────────────────────────────────
Write-Host "`n=== RESULT ===" -ForegroundColor Cyan
Write-Host ("  passed: {0}" -f $pass) -ForegroundColor Green
if ($fail -gt 0) {
    Write-Host ("  failed: {0}" -f $fail) -ForegroundColor Red
    Write-Host '  THE RELEASE FEED IS NOT SAFE TO PUBLISH' -ForegroundColor Red
    exit 1
}
Write-Host '  failed: 0' -ForegroundColor Green
Write-Host '  release feed is public, token-free, and pinned to the right repo' -ForegroundColor Green
exit 0
